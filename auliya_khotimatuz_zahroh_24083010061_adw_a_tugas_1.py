import pandas as pd
import matplotlib.pyplot as plt
from statsmodels.tsa.stattools import adfuller, kpss
from statsmodels.graphics.tsaplots import plot_acf

# 1. Load Data dari Sheet 4
file_path = 'Rancangan Keberlanjutan Rantai Pasok PasarTani.xlsx'
df = pd.read_excel(file_path, sheet_name='4_Jadwal_Tanam_Panen')

# 2. Data Cleaning
# Ekstrak angkanya saja dari teks (misal: "30 Ikat" menjadi 30.0)
df['Target Panen Harian'] = df['Target Panen Harian'].astype(str).str.extract(r'(\d+\.?\d*)').astype(float)
# Isi data yang kosong dengan angka 0
df['Target Panen Harian'] = df['Target Panen Harian'].fillna(0)

# Menggunakan 'Tanggal Mulai Panen' sebagai penanda waktu
df['Tanggal Mulai Panen'] = pd.to_datetime(df['Tanggal Mulai Panen'])
df = df.sort_values('Tanggal Mulai Panen')

# Agregasi (Jumlahkan) hasil panen per hari
df_daily = df.groupby('Tanggal Mulai Panen')['Target Panen Harian'].sum().reset_index()
df_daily.set_index('Tanggal Mulai Panen', inplace=True)


# 3. Visualisasi EDA & Rolling Statistics
plt.figure(figsize=(12, 6))
plt.plot(df_daily.index, df_daily['Target Panen Harian'], label='Target Panen Harian', color='blue')
plt.plot(df_daily['Target Panen Harian'].rolling(window=7).mean(), label='Rolling Mean (7 Hari)', color='red')
plt.plot(df_daily['Target Panen Harian'].rolling(window=7).std(), label='Rolling Std (7 Hari)', color='black')
plt.title('Eksplorasi Data Target Panen Bergilir Urban Farming BRIDA')
plt.xlabel('Tanggal Mulai Panen')
plt.ylabel('Total Target Panen')
plt.legend()
plt.show()

# 4. Visualisasi ACF (Autocorrelation Function) untuk melihat pola musiman
plt.figure(figsize=(10, 4))
plot_acf(df_daily['Target Panen Harian'].dropna(), lags=30, alpha=0.05)
plt.title('Plot ACF (Identifikasi Pola Musiman)')
plt.show()

# 5. Uji Statistik Stasioneritas (ADF & KPSS)
print("=== Hasil Augmented Dickey-Fuller (ADF) Test ===")
adf_result = adfuller(df_daily['Target Panen Harian'].dropna())
print(f'ADF Statistic: {adf_result[0]:.4f}')
print(f'p-value: {adf_result[1]:.4f}')
print("Kesimpulan ADF: " + ("Stasioner" if adf_result[1] < 0.05 else "Non-Stasioner (Gagal tolak H0)"))

print("\n=== Hasil KPSS Test ===")
kpss_result = kpss(df_daily['Target Panen Harian'].dropna(), regression='c', nlags='auto')
print(f'KPSS Statistic: {kpss_result[0]:.4f}')
print(f'p-value: {kpss_result[1]:.4f}')
print("Kesimpulan KPSS: " + ("Non-Stasioner (Tolak H0)" if kpss_result[1] < 0.05 else "Stasioner"))